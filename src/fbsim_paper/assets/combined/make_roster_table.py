"""The model roster of Appendix A, data/roster_table.tex, from the paper checkout's CSVs. Standard library only:
    python3 make_roster_table.py --paper-root PAPER

Models, ECI and the requested reasoning setting come from freeciv/models_v2.csv, ForecastBench overall from
micropolis/model_scores.csv, and Starsim's mean reasoning tokens per call from starsim/starsim_excess_long.csv.
One column, FreeCiv/Micropolis, holds the reasoning setting of both worlds: Micropolis's run (models-loeff.json5 on
forecastbench-sim's micropolis branch) requested the same setting for every model, which no paper file records.
"""
import argparse, csv
from pathlib import Path

ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument("--paper-root", type=Path, required=True)
DATA = ap.parse_args().paper_root.resolve() / "data"
OUT = DATA / "roster_table.tex"

# Starsim's five sets as scored, each call counted once (the interventional rungs pooled).
STARSIM_SETS = [("binary", "interventional", "c90"), ("binary", "interventional", "hold"), ("binary", "unconditional", "-"),
                ("continuous", "interventional", "c25"), ("continuous", "interventional", "c50"),
                ("continuous", "interventional", "c90"), ("continuous", "unconditional", "-")]

def setting(r):
    mode = r["reasoning_mode"]
    if mode == "effort":
        return r["effort"]
    if mode == "budget":
        return f"budget {int(float(r['budget'])):,}"
    if mode in ("none", "disabled"):
        return mode
    raise ValueError(f"{r['openrouter_id']}: reasoning_mode {mode!r}")

def tex(s):
    return s.replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")

models = list(csv.DictReader(open(DATA / "freeciv" / "models_v2.csv")))
fb = {r["slug"]: r["FBOverall"] for r in csv.DictReader(open(DATA / "micropolis" / "model_scores.csv"))}
calls, tokens = {}, {}
for r in csv.DictReader(open(DATA / "starsim" / "starsim_excess_long.csv")):
    if r["horizon"] == "pooled" and (r["question_type"], r["condition"], r["rung"]) in STARSIM_SETS:
        n = int(r["n_calls"])
        calls[r["model"]] = calls.get(r["model"], 0) + n
        tokens[r["model"]] = tokens.get(r["model"], 0) + n * float(r["reasoning_tokens_mean"])
ids = [r["openrouter_id"] for r in models]
if len(ids) != 24 or set(ids) != set(calls) or not set(ids) <= set(fb):
    raise ValueError("models_v2.csv, model_scores.csv and starsim_excess_long.csv disagree on the roster")

lines = ["% Generated by forecastbench-sim-paper/src/fbsim_paper/assets/combined/make_roster_table.py; do not edit by hand.",
         r"\begin{tabular}{@{}l r r l r@{}}", r"\toprule",
         r"Model & ECI & FB & FreeCiv/Micropolis & Starsim tokens \\", r"\midrule"]
for r in sorted(models, key=lambda r: -float(r["eci"])):
    m = r["openrouter_id"]
    lines.append(" & ".join([tex(r["name"].split(": ", 1)[-1].strip()), f"{float(r['eci']):.2f}",
                             f"{float(fb[m]):.1f}" if fb[m] else "--", setting(r), f"{tokens[m] / calls[m]:,.0f}"]) + r" \\")
lines += [r"\bottomrule", r"\end{tabular}"]
text = "\n".join(lines) + "\n"
if not OUT.exists() or OUT.read_text() != text:
    OUT.write_text(text)
    print(f"wrote {OUT}")
