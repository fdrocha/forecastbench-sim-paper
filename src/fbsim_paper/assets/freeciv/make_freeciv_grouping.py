#!/usr/bin/env python
"""FreeCiv one question per prompt (September 9) against the grouped prompts (September 20), Appendix D.

    python src/fbsim_paper/assets/freeciv/make_freeciv_grouping.py --one RUN1_DIR --grouped RUN2_DIR --shuffled SHUFFLED_DIR --paper-root PAPER

Reads score_items.csv.gz of the three scored runs: the run of September 9 (one question per prompt), the reported
grouped run and the first grouped run, which shuffled the sets.  Writes data/appendix_tables/freeciv_grouping.tex
(mean over the 24 models and sign-adjusted Spearman rho with ECI per run, and the rank correlation between the runs),
data/freeciv_grouping_macros.tex (\\FCGroup... macros for the text) and data/freeciv/freeciv_grouping.json.
Run after make_freeciv_forecast_files.py: the 231 shared mid-range questions come from its freeciv_binary_forecasts.csv.
"""
import argparse, json, math
from datetime import date
from pathlib import Path

import pandas as pd
from scipy.stats import spearmanr

from _common import DATA, PAPER_DATA, TABLES, fmt, load_capability, rel

ap = argparse.ArgumentParser()
ap.add_argument("--one", required=True); ap.add_argument("--grouped", required=True); ap.add_argument("--shuffled", required=True)
ap.add_argument("--paper-root")
a = ap.parse_args()

SETS = [("bank", "excess_brier", "Mid-range, excess Brier"), ("tails", "excess_bits", "Tail, excess bits"),
        ("mirrors", "excess_brier", "Mirror, excess Brier"), ("continuous", "excess_ncrps_global", "Continuous, excess nCRPS")]
eci = load_capability().eci


ITEMS = {}


def per_model(run, s, col):
    """Each model's mean of col over set s."""
    if run not in ITEMS:
        ITEMS[run] = pd.read_csv(Path(run) / "scores_v1" / "score_items.csv.gz", low_memory=False)
    return ITEMS[run][ITEMS[run].set == s].groupby("model")[col].mean()


def rho(v):
    return float(spearmanr(eci[v.index], -v)[0])


def max_move(x, y):
    return int((x.rank() - y.rank()).abs().max())


rows, N = [], dict(generated=str(date.today()), runs=dict(one=Path(a.one).name, grouped=Path(a.grouped).name, shuffled=Path(a.shuffled).name), sets={})
for s, col, label in SETS:
    one, grp, shuf = (per_model(r, s, col) for r in (a.one, a.grouped, a.shuffled))
    assert set(one.index) == set(grp.index) == set(shuf.index) == set(eci.index)
    one, shuf = one[grp.index], shuf[grp.index]
    N["sets"][s] = d = dict(mean_one=float(one.mean()), mean_grouped=float(grp.mean()), mean_shuffled=float(shuf.mean()),
                            rho_one=rho(one), rho_grouped=rho(grp), rank_corr=float(spearmanr(one, grp)[0]), max_rank_move=max_move(one, grp),
                            shuffled_rank_corr=float(spearmanr(shuf, grp)[0]))
    rows.append(f"{label} & {fmt(d['mean_one'])} & {fmt(d['rho_one'], 2)} & {fmt(d['mean_grouped'])} & {fmt(d['rho_grouped'], 2)} & {fmt(d['rank_corr'], 2)} \\\\")
S = N["sets"]

# the 231 mid-range questions asked in both prompts (the single-prompt forecast is a natural-conditional cell's turn 1)
b = pd.read_csv(DATA / "freeciv_binary_forecasts.csv")
m = b[b.section == "mid-range"]
j = m[m.prompt == "single"].merge(m[m.prompt == "grouped"], on=["model", "question_id"], suffixes=("_s", "_g"))
N["overlap"] = dict(questions=int(j.question_id.nunique()), pairs=len(j), forecast_single=float(j.forecast_s.mean()), forecast_grouped=float(j.forecast_g.mean()),
                    truth=float(j.real_prob_s.mean()))
(DATA / "freeciv_grouping.json").write_text(json.dumps(N, indent=1))

head = ["% Generated by forecastbench-sim-paper/src/fbsim_paper/assets/freeciv/make_freeciv_grouping.py from the score_items of the three runs; do not edit by hand."]
(TABLES / "freeciv_grouping.tex").write_text("\n".join(head + [
    r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
    r" & \multicolumn{2}{c}{One per prompt} & \multicolumn{2}{c}{Grouped} & \\", r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
    r"Set & Mean & $\rho$ & Mean & $\rho$ & Rank corr. \\", r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}"]) + "\n")

ORDER = ["bank", "tails", "mirrors", "continuous"]
moves = [S[s]["max_rank_move"] for s in ORDER]
WORDS = {"bank": "mid-range", "tails": "tail", "mirrors": "mirror", "continuous": "continuous"}


def losses(sets, verb):
    """'Tail loss falls', 'mid-range, mirror and continuous losses rise'."""
    names = [WORDS[s] for s in sets]
    text = names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]
    return text + (f" loss {verb}s" if len(names) == 1 else f" losses {verb}")


falls = [s for s in ORDER if S[s]["mean_grouped"] < S[s]["mean_one"]]
rises = [s for s in ORDER if s not in falls]
direction = (f"All four losses {'fall' if falls else 'rise'}" if not (falls and rises) else losses(falls, "fall") + " while " + losses(rises, "rise"))
M = {
    "FCGroupDirection": direction[0].upper() + direction[1:],
    "FCGroupRhoChangeMax": f"{max(abs(S[s]['rho_grouped'] - S[s]['rho_one']) for s in ORDER):.2f}",
    "FCGroupRankCorrLo": f"{min(S[s]['rank_corr'] for s in ORDER):.2f}", "FCGroupRankCorrHi": f"{max(S[s]['rank_corr'] for s in ORDER):.2f}",
    "FCGroupMoves": ", ".join(map(str, moves[:-1])) + f" and {moves[-1]}",
    "FCGroupOverlapSingle": f"{N['overlap']['forecast_single']:.2f}", "FCGroupOverlapGrouped": f"{N['overlap']['forecast_grouped']:.2f}",
    "FCGroupOverlapTruth": f"{N['overlap']['truth']:.2f}",
    "FCGroupShuffledDiffMax": f"{math.ceil(1000 * max(abs(S[s]['mean_shuffled'] - S[s]['mean_grouped']) for s in ORDER)) / 1000:.3f}",   # a bound: rounded up
    "FCGroupShuffledRankLo": f"{min(S[s]['shuffled_rank_corr'] for s in ORDER):.2f}", "FCGroupShuffledRankHi": f"{max(S[s]['shuffled_rank_corr'] for s in ORDER):.2f}",
}
(PAPER_DATA / "freeciv_grouping_macros.tex").write_text(
    head[0].replace("the score_items of the three runs", "the three runs") + "\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in M.items()))
print(f"wrote {rel(TABLES / 'freeciv_grouping.tex')}, {rel(PAPER_DATA / 'freeciv_grouping_macros.tex')} and {rel(DATA / 'freeciv_grouping.json')}")
for k, v in M.items():
    print(f"  {k:24s} {v}")
