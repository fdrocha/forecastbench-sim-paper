"""The baselines against the models: the prose macros, and the appendix tables of binary and continuous alternatives.
Standard library only:
    python3 make_baseline_table.py --paper-root PAPER

Reads each world's baseline JSON and the model scores the combined score fits; writes data/baseline_macros.tex and
data/appendix_tables/{binary,continuous}_baselines.tex. Lower is better; a model beats a baseline when its mean score
is lower.
"""
import argparse, csv, json, statistics
from pathlib import Path

ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument("--paper-root", type=Path, required=True)
DATA = ap.parse_args().paper_root.resolve() / "data"
read = lambda p: list(csv.DictReader(open(DATA / p)))

mp, fc = (json.load(open(DATA / p)) for p in ("micropolis/micropolis_baselines.json", "freeciv/freeciv_baselines.json"))
mpm, fcm = read("micropolis/micropolis_model_scores.csv"), read("freeciv/freeciv_results_wide.csv")
MODELS = {("MP", "Mid"): [float(r["mid_range_excess_brier"]) for r in mpm], ("MP", "Tail"): [float(r["tail_excess_bits"]) for r in mpm],
          ("FC", "Mid"): [float(r["bank_all_excess_brier"]) for r in fcm], ("FC", "Tail"): [float(r["tails_all_excess_bits"]) for r in fcm]}
VARIANTS = {"MP": mp["binary_variants"], "FC": fc["binary_variants"]}
beat = lambda models, b: sum(m < b for m in models)

def fmt(x):
    return f"{x:.2f}" if x >= 1 else f"{x:.3f}"

macros = ["% Generated by forecastbench-sim-paper/src/fbsim_paper/assets/combined/make_baseline_table.py; do not edit by hand.",
          "% \\BL<world><set>: the base rate's score; Beat: models scoring below it; N: models; Best, Median: the best and median model."]
def macro(name, value):
    macros.append(f"\\newcommand{{\\BL{name}}}{{{value}}}")
for (w, s), models in MODELS.items():
    b = VARIANTS[w]["question_horizon"]["mid" if s == "Mid" else "tail"]
    macro(w + s, fmt(b)); macro(w + s + "Beat", beat(models, b)); macro(w + s + "N", len(models))
    macro(w + s + "Best", fmt(min(models))); macro(w + s + "Median", fmt(statistics.median(models)))
# continuous: the climatological change in every world, and Starsim's SIR forecast
ss = json.load(open(DATA / "starsim/starsim_baselines.json"))
ssm = [float(r["excess"]) for r in read("starsim/starsim_excess_long.csv") if r["horizon"] == "pooled" and r["complete"] == "True"
       and r["question_type"] == "continuous" and r["condition"] == "unconditional"]
CONT = {"MPCont": (mp["excess_ncrps"], [float(r["excess_ncrps"]) for r in mpm]),
        "FCCont": (fc["continuous_all_excess_ncrps_global"], [float(r["continuous_all_excess_ncrps_global"]) for r in fcm]),
        "SSCont": (ss["unconditional"], ssm), "SSContSIR": (ss["unconditional_sir"], ssm)}
for stem, (b, models) in CONT.items():
    macro(stem, fmt(b)); macro(stem + "Beat", beat(models, b)); macro(stem + "N", len(models))
    macro(stem + "Best", fmt(min(models))); macro(stem + "Median", fmt(statistics.median(models)))
# conditionals: independence, the unconditional baseline ignoring the condition
ssi = [float(r["excess"]) for r in read("starsim/starsim_excess_long.csv") if r["horizon"] == "pooled" and r["complete"] == "True"
       and r["question_type"] == "continuous" and r["condition"] == "interventional" and r["rung"] == "pooled(c25,c50,c90)"]
fcn = [float(r["natcond_all_excess_t2"]) for r in fcm]
for stem, (b, models) in {"FCNatcond": (fc["natcond_all_excess_t2"], fcn), "SSInt": (ss["interventional"], ssi)}.items():
    macro(stem, fmt(b)); macro(stem + "Beat", beat(models, b)); macro(stem + "N", len(models))
    macro(stem + "Best", fmt(min(models))); macro(stem + "Median", fmt(statistics.median(models)))
# the same with the true unconditional answer: p(Y), or the no-vaccine distribution
macro("FCNatcondTrueP", fmt(fc["natcond_true_py_excess_t2"])); macro("FCNatcondTruePBeat", beat(fcn, fc["natcond_true_py_excess_t2"]))
macro("SSIntTrueNoVax", fmt(ss["interventional_true_no_vaccine"])); macro("SSIntTrueNoVaxBeat", beat(ssi, ss["interventional_true_no_vaccine"]))
macro("SSIntOwnBeat", ss["n_models_beat_own_no_vaccine"]); macro("SSIntOwnN", ss["n_models"])
macro("SSIntOwn", fmt(statistics.mean(v["reused"] for v in ss["own_no_vaccine"].values())))
err = [abs(ss["sir_forecast"][i] / ss["truth_median"][i] - 1) for i in ss["sir_forecast"]]
macro("SSSIRErrMin", f"{100 * min(err):.0f}"); macro("SSSIRErrMax", f"{100 * max(err):.0f}")
# the constant references the paper already quotes, for the same comparison
for (w, s), models in MODELS.items():
    const = VARIANTS[w]["constant"]["mid" if s == "Mid" else "tail"]
    macro(w + s + "Const", fmt(const)); macro(w + s + "ConstBeat", beat(models, const))
# FreeCiv: the asked-question pool, the 1,100 selected questions pooled, and the models' forecast levels
macro("FCMidAsked", fmt(fc["binary_variants"]["question_horizon_asked_pool"]["mid"]))
macro("FCTailAsked", fmt(fc["binary_variants"]["question_horizon_asked_pool"]["tail"]))
macro("FCCandidates", f"{fc['n']['candidates']:,}"); macro("FCContCandidates", f"{fc['n']['continuous_candidates']:,}")
macro("FCQuestionsPerRate", f"{fc['questions_per_base_rate']['median']:.0f}")
pooled = [(750 * float(r["bank_all_excess_brier"]) + 300 * float(r["tails_all_excess_brier"]) + 50 * float(r["mirrors_all_excess_brier"])) / 1100
          for r in fcm]
macro("FCSelected", fmt(fc["selected_excess_brier"])); macro("FCSelectedBeat", beat(pooled, fc["selected_excess_brier"]))
macro("FCSelectedBest", fmt(min(pooled)))
L = fc["forecast_levels"]
for s, key in (("Mid", "mid"), ("Tail", "tail")):
    macro(f"FC{s}MeanForecast", f"{L[key]['mean_forecast']:.2f}"); macro(f"FC{s}MeanQ", f"{L[key]['mean_q']:.2f}")
    macro(f"FC{s}MeanRate", f"{L[key]['mean_base_rate']:.2f}")
macro("FCMidCorrForecast", f"{L['mid']['corr_forecast_q']:.2f}")
macro("FCMidCorrForecastMax", f"{max(L['mid']['corr_forecast_q_models']):.2f}")
macro("FCMidCorrRate", f"{L['mid']['corr_base_rate_q']:.2f}")
macro("FCRankCorrForecastLevel", f"{L['rank_corr_mean_forecast_mid_tail']:.2f}")

# appendix: the alternatives, each cell "score (models beating it)"
ROWS = [("constant", "Constant 0.5 (mid-range) or 0.05 (tail)$^\\dagger$"),
        ("simulator", "One rate per simulation"),
        ("simulator_horizon", "Per simulation and horizon"),
        ("question", "Per question"),
        ("question_horizon", "\\textbf{Per question and horizon (used)}"),
        ("question_horizon_in_sample", "\\quad including the forecast world"),
        ("question_horizon_within_set", "\\quad within the question's set$^\\dagger$"),
        ("family_horizon", "\\quad FreeCiv family instead of template"),
        ("question_horizon_asked_pool", "\\quad FreeCiv asked questions instead of candidates")]
rows = []
for key, label in ROWS:
    cells = []
    for w in ("MP", "FC"):
        for s in ("Mid", "Tail"):
            v = VARIANTS[w].get(key)
            cells.append("--" if v is None else f"{fmt(v['mid' if s == 'Mid' else 'tail'])} ({beat(MODELS[w, s], v['mid' if s == 'Mid' else 'tail'])})")
    rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
table = ["% Generated by forecastbench-sim-paper/src/fbsim_paper/assets/combined/make_baseline_table.py; do not edit by hand.",
         "% Each world's binary_variants in its baselines JSON; in parentheses, models (of 24) with a lower mean score.",
         r"\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{lrrrr}", r"\toprule",
         r" & \multicolumn{2}{c}{Micropolis} & \multicolumn{2}{c}{FreeCiv} \\ \cmidrule(lr){2-3} \cmidrule(lr){4-5}",
         r"Base rate & Mid-range & Tail & Mid-range & Tail \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]

# appendix: the continuous alternatives, the same way
CONT_VARIANTS = {"MP": mp["continuous_variants"], "FC": fc["continuous_variants"], "SS": ss["continuous_variants"]}
CONT_MODELS = {"MP": CONT["MPCont"][1], "FC": CONT["FCCont"][1], "SS": ssm}
CONT_ROWS = [("change", "\\textbf{Climatological change (used)}"),
             ("last", "Persistence"),
             ("climatology", "Other worlds' values instead of changes"),
             ("sir", "SIR forecast")]
rows = []
for key, label in CONT_ROWS:
    cells = []
    for w in ("MP", "FC", "SS"):
        v = CONT_VARIANTS[w].get(key)
        cells.append("--" if v is None else f"{fmt(v)} ({beat(CONT_MODELS[w], v)})")
    rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
cont_table = ["% Generated by forecastbench-sim-paper/src/fbsim_paper/assets/combined/make_baseline_table.py; do not edit by hand.",
              "% Each world's continuous_variants in its baselines JSON; in parentheses, models with a lower mean score.",
              r"\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{lrrr}", r"\toprule",
              r"Forecast & Micropolis & FreeCiv & Starsim \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]
for path, text in [(DATA / "appendix_tables/binary_baselines.tex", "\n".join(table) + "\n"),
                   (DATA / "appendix_tables/continuous_baselines.tex", "\n".join(cont_table) + "\n"),
                   (DATA / "baseline_macros.tex", "\n".join(macros) + "\n")]:
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
        print(f"wrote {path}")
